// מקומות בטבלה.
//
// המקום נקבע לפי הניקוד ולא לפי הסדר ברשימה: שני שחקנים עם 2.3 חולקים
// את המקום השני, והבא אחריהם הוא רביעי ("1, 2, 2, 4"). קודם המקום היה
// האינדקס, ושחקן קיבל ארד על אותו ניקוד שחברו קיבל עליו כסף.

const norm = (s) => Math.round((Number(s) || 0) * 10) / 10;

/** מקום (מ-1) לכל ניקוד ברשימה. לא מניח שהרשימה ממוינת. */
export const placesFor = (scores) => {
  const vals = scores.map(norm);
  return vals.map((v) => 1 + vals.filter((o) => o > v).length);
};

/** האם מישהו כבר צבר נקודות. בלי זה אין טעם במדליות - כולם על 0. */
export const anyScored = (scores) => scores.some((s) => norm(s) > 0);
